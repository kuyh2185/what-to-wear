export const rand=a=>a[Math.floor(Math.random()*a.length)];
export const shuffle=a=>{a=a.slice();for(let i=a.length-1;i>0;i--){const j=Math.floor(Math.random()*(i+1));[a[i],a[j]]=[a[j],a[i]];}return a;};
export const bandOf=t=>BANDS.findIndex(b=>t>=b.min&&t<=b.max);
export const keyOf=i=>`${i.cat}|${i.name}|${i.shape}`;
export const weightOf=(i,rules)=>rules.reduce((w,[re,x])=>re.test(keyOf(i))?w*x:w,1);
export function wpick(pool,rules){
  const ws=pool.map(i=>weightOf(i,rules)), tot=ws.reduce((a,b)=>a+b,0);
  let r=Math.random()*tot;
  for(let i=0;i<pool.length;i++){r-=ws[i];if(r<=0)return pool[i];}
  return pool[pool.length-1];
}
export function evaluate(c,rules){
  let score=1; const good=[],bad=[];
  for(const p of c.pieces){const k=keyOf(p);
    for(const [re,x,note] of rules)if(re.test(k)){score*=x;(x>1?good:bad).push(note);}
  }
  const v=score>=1.5?['good','잘 어울려요']:score<.75?['warn','주의']:['ok','무난해요'];
  return {score,cls:v[0],label:v[1],good:[...new Set(good)],bad:[...new Set(bad)]};
}

export function pickColor(item,pal,used){
  let o=item.colors.filter(c=>pal.includes(c)&&!used.has(c));
  if(!o.length)o=item.colors.filter(c=>NEUTRAL.includes(c)&&!used.has(c));
  if(!o.length)o=item.colors.filter(c=>!used.has(c));
  if(!o.length)o=item.colors;
  return rand(o);
}

// strict: leave out items the rules advise against (weight < 1) instead of only picking them less often
export function makeCombo(gender,t,bigGap,style,rules,strict=false){
  const b=bandOf(t), items=DATA[gender], pal=rand(PALETTES[gender]);
  const pool=(cat,band)=>{
    let inBand=items.filter(i=>i.cat===cat&&band>=i.b0&&band<=i.b1);
    if(strict){const ok=inBand.filter(i=>weightOf(i,rules)>=1);if(ok.length)inBand=ok;}
    const st=inBand.filter(i=>i.styles.includes(style));
    return st.length?st:inBand;
  };
  const used=new Set(), pieces=[];
  const add=(cat,band=b)=>{
    const p=pool(cat,band); if(!p.length)return null;
    const it=wpick(p,rules), color=pickColor(it,pal.c,used);
    used.add(color);
    const piece={...it,color};
    if(PRODUCTS[it.name])piece.product=rand(PRODUCTS[it.name]);
    pieces.push(piece); return piece;
  };
  let chance=OUTER_CHANCE[b], outerBand=b;
  if(bigGap){chance=Math.max(chance,b>=7?.6:1); outerBand=Math.max(0,bandOf(t-8));}
  if(Math.random()<chance)add('outer',outerBand);
  const dressPool=gender==='women'?pool('dress',b):[];
  let lower=null;
  if(dressPool.length&&dressPool.some(d=>d.styles.includes(style))&&Math.random()<.28){lower=add('dress');}
  else{add('top');lower=add('bottom');}
  add('shoes');
  if(b===0||Math.random()<.7)add('acc');
  const bareLegs=lower&&(lower.cat==='dress'||lower.shape==='skirt'||lower.shape==='shorts');
  if(gender==='women'&&bareLegs&&b<=3)pieces.push({cat:'leg',name:b<=1?'기모 스타킹':'스타킹',color:'블랙',shape:''});
  const order=['outer','top','dress','bottom','shoes','acc','leg'];
  pieces.sort((a,c)=>order.indexOf(a.cat)-order.indexOf(c.cat));
  return {style,pal:pal.name,band:b,pieces,sig:style+':'+pieces.map(p=>p.color+p.name).join('/')};
}
